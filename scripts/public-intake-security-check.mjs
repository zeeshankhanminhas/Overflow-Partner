import {readFileSync,existsSync} from 'node:fs';
const checks=[];const read=file=>readFileSync(file,'utf8');
const check=(label,condition)=>checks.push({label,pass:Boolean(condition)});
const intake=read('app/api/intake/route.ts');
const pending=read('app/api/intake/confirm/route.ts');
const finalise=read('lib/public-intake/finalize.ts');
const form=read('components/EnquiryForm.tsx');
const migration=read('supabase/migrations/20261108110000_public_intake_security.sql');
const login=read('app/login/page.tsx');const actions=read('app/login/actions.ts');
const cookie=read('components/CookieConsent.tsx');
const layout=read('app/layout.tsx');const next=read('next.config.ts');
check('API checks Turnstile server-side',intake.includes('checkTurnstile(')&&intake.includes('https://challenges.cloudflare.com/turnstile/v0/siteverify'));
check('API does not trust browser-only CAPTCHA',intake.includes('TURNSTILE_SECRET_KEY')&&intake.includes('turnstile_token'));
check('API uses atomic database quota',intake.includes("op_public_intake_claim_quota")&&migration.includes("pg_advisory_xact_lock"));
check('API rejects absent CAPTCHA configuration',intake.includes('!secret||!hashSecret'));
check('Honeypot receives no notifications',intake.includes('if(payload.company_website)return'));
check('Unverified intake does not write CRM',!intake.includes(".from('prospects')")&&!intake.includes(".from('contacts')")&&!intake.includes(".from('companies')"));
check('Pending record uses hashed verification token',intake.includes("createHash('sha256')")&&intake.includes('token_hash:tokenHash'));
check('Confirmation link requires explicit POST',pending.includes('export async function POST(')&&!pending.includes('export async function GET('));
check('Confirmation claim is atomic, time limited and not replayable',migration.includes('op_public_intake_claim_confirmation')&&migration.includes('finalised_at is null')&&migration.includes("interval '10 minutes'"));
check('Verified intake reuses governed workflow',pending.includes('finalizeVerifiedEnquiry')&&finalise.includes("scenario: 'requirements.requested'"));
check('No automatic Step 2 reminder burst',!finalise.includes("scenario: 'requirements.reminder'"));
check('QA isolation retained',intake.includes('isKnownIsolatedQaBackend')&&pending.includes('isKnownIsolatedQaBackend'));
check('Form includes honeypot',form.includes('name="company_website"'));
check('Form includes CAPTCHA response',form.includes("'cf-turnstile-response'"));
check('Form matches six service catalogue',form.includes('services.map('));
check('Consent is required for analytics',cookie.includes("choice==='accepted'")&&cookie.includes('<Analytics/>')&&cookie.includes('<SpeedInsights/>')&&!layout.includes('<Analytics />'));
check('Login query text is fixed to allowlisted codes',login.includes('messages[error]')&&!login.includes('{error}</p>'));
check('Login redirects with safe codes',!actions.includes('encodeURIComponent(error?.message')&&actions.includes('/login?error=invalid'));
check('Global anti-clickjacking and MIME headers',next.includes("X-Frame-Options")&&next.includes("X-Content-Type-Options"));
check('Sensitive files excluded by gitignore',existsSync('.gitignore')&&read('.gitignore').includes('.env.*'));
let failed=0;for(const item of checks){console.log((item.pass?'PASS ':'FAIL ')+item.label);if(!item.pass)failed++;}
console.log(`Public security checks: ${checks.length-failed}/${checks.length} passed`);
if(failed)process.exit(1);
